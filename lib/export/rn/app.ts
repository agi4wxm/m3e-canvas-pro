/* A document's mobile app as files, for the export to put under apps/mobile (the monorepo layout) or anywhere else:
 *
 *   src/generated/theme.ts          the theme the kit reads (lib/export/rn/theme.ts)
 *   src/generated/icons.ts          the glyphs of every icon the screens and the kit draw, offline
 *   src/generated/screens/*.tsx     one component per screen (lib/export/rn/print.ts)
 *   src/generated/screens/index.ts  the screens by key, the first screen, the flows
 *   src/generated/App.tsx           the app: theme, icons and a small navigator over the screens
 *   src/kit/**                      the kit (rn/src/kit), copied as it is, when its files are given
 *
 * All of it is generated code: changing it by hand is changing the design's output, which the next export replaces.
 * Custom code (written by a person or an AI agent) goes in src/custom, which an export never writes. */

export type RnAppFile = { path: string; text: string; kind: "generated" | "kit" };

export type RnApp = { files: RnAppFile[]; warnings: RnWarning[]; theme: RnTheme; screens: RnScreens };

const HEAD = "// Generated by M3E Canvas from the design. Do not edit: change the design and export again.";

/** the theme as a module the kit's type checks */
export const themeModule = (theme: RnTheme, kitImport = "../kit") => `${HEAD}\nimport type { KitTheme } from ${str(kitImport)};\n\nexport const theme: KitTheme = ${JSON.stringify(theme, null, 1)};\n`;

/** the glyphs as a module */
export const iconsModule = (data: unknown, kitImport = "../kit") => `${HEAD}\nimport type { IconData } from ${str(kitImport)};\n\nexport const icons: IconData = ${JSON.stringify(data)};\n`;

/** the kinds of picture Metro bundles and expo-image draws on every platform, and the extension each file takes */
const PICTURE_KINDS: Record<string, string> = { png: "png", jpeg: "jpg", jpg: "jpg", gif: "gif", webp: "webp" };

/** The pictures a document holds as data (a data: URL: a picture the author picked from a file), as files an app on
 *  the kit bundles. Metro bundles a picture only where code requires its file, so each one is written once (`files`,
 *  by its path from the app's root) and required once in the images module (`module`), which the screens read; the
 *  kit's image props take what the require gives (rn/src/kit/parts.ts `sourceOf`). */
export class RnPictures {
  /** each picture by its data: the name the screens read it by, and its file's name */
  private seen = new Map<string, { name: string; file: string }>();
  /** each picture's file, by its path from the app's root */
  readonly files: Record<string, Uint8Array> = {};

  /** `dir`: where the files go, from the app's root; `from`: that folder as the images module requires it */
  constructor(
    private readonly dir: string,
    private readonly from: string,
  ) {}

  /** the name the screens read a picture by, its file written the first time; none for what Metro does not bundle */
  readonly name = (data: string): string | undefined => {
    const seen = this.seen.get(data);
    if (seen) return seen.name;
    const m = /^data:image\/([a-z]+);base64,([A-Za-z0-9+/=\s]+)$/.exec(data);
    const ext = m ? PICTURE_KINDS[m[1]] : undefined;
    if (!m || !ext) return undefined;
    const name = `image${this.seen.size + 1}`;
    const file = `${name}.${ext}`;
    this.seen.set(data, { name, file });
    this.files[`${this.dir}/${file}`] = fromBase64(m[2]);
    return name;
  };

  /** whether any picture was written */
  get any(): boolean {
    return this.seen.size > 0;
  }

  /** The images module: a require of each picture's file, by its name. `requireRule`: the app's ESLint config forbids
   *  require (typescript-eslint's recommended rules, as the product's root config has them; Expo's has not). */
  module(o: { requireRule?: boolean } = {}): string {
    return [
      HEAD,
      ...(o.requireRule ? ["/* eslint-disable @typescript-eslint/no-require-imports -- Metro bundles a picture only where code requires its file */"] : []),
      "",
      "/** the pictures the design holds, as files the app bundles: what the kit's image props take */",
      "export const IMAGES = {",
      ...[...this.seen.values()].map((x) => `  ${x.name}: require(${str(`${this.from}/${x.file}`)}),`),
      "};",
      "",
    ].join("\n");
  }
}

/** the app over the printed screens: its memory (the variables, the parts hidden at the start, the snackbar) around a
 *  small navigator */
export const appModule = (kitImport = "../kit", memory: Pick<RnScreens, "hidden" | "vars"> = { hidden: [], vars: [] }) =>
  [
    HEAD,
    'import { SafeAreaProvider, initialWindowMetrics } from "react-native-safe-area-context";',
    `import { AppProvider, ScreenStack, SnackHost, ThemeProvider, registerIcons, type AppVar } from ${str(kitImport)};`,
    'import { icons } from "./icons";',
    'import { INITIAL, SCREENS } from "./screens";',
    'import { theme } from "./theme";',
    "",
    "registerIcons(icons);",
    "",
    "/** the design's variables, and the parts hidden until a tap shows them */",
    `const VARS: AppVar[] = ${expr(memory.vars)};`,
    `const HIDDEN: string[] = ${expr(memory.hidden)};`,
    "",
    "/** the design's app: its theme (light or dark as the device is, unless `dark` says), its screens and where taps go */",
    "export function App({ dark, initial = INITIAL }: { dark?: boolean; initial?: string }) {",
    "  return (",
    "    <SafeAreaProvider initialMetrics={initialWindowMetrics}>",
    "      <ThemeProvider theme={theme} dark={dark}>",
    "        <AppProvider vars={VARS} hidden={HIDDEN}>",
    "          <ScreenStack screens={SCREENS} initial={initial} />",
    "          <SnackHost />",
    "        </AppProvider>",
    "      </ThemeProvider>",
    "    </SafeAreaProvider>",
    "  );",
    "}",
    "",
  ].join("\n");

/** Every file of a document's mobile app. `kit` is the kit's own files by their path under rn/src/kit (see
 *  `readKitSources`); left out, the app's files assume the kit is already at src/kit. */
export async function printRnApp(doc: Doc, widths: Record<string, number>, o: RnPrintOptions & { kit?: Record<string, string> } = {}): Promise<RnApp> {
  const screens = printRnScreens(doc, widths, { kitImport: "../../kit", ...o });
  const theme = rnThemeOf(doc);
  /* a document's own icons (svg:<id>) are its drawings, carried with the glyphs */
  const icons = await rnIconData([theme.icons], [...screens.icons, ...KIT_ICONS]);
  for (const [id, markup] of Object.entries(doc.icons ?? {})) {
    const box = /viewBox="([\d.\s-]+)"/.exec(markup)?.[1]?.trim().split(/\s+/).map(Number);
    const body = markup.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
    icons.glyphs[`m3e-doc:${id}`] = [body, box?.[2] ?? 24, box?.[3] ?? 24];
  }
  const files: RnAppFile[] = [
    { path: "src/generated/theme.ts", text: themeModule(theme), kind: "generated" },
    { path: "src/generated/icons.ts", text: iconsModule(icons), kind: "generated" },
    ...screens.screens.map((s): RnAppFile => ({ path: `src/generated/screens/${s.component}.tsx`, text: s.source, kind: "generated" })),
    { path: "src/generated/screens/index.ts", text: screensIndex(screens), kind: "generated" },
    { path: "src/generated/App.tsx", text: appModule("../kit", screens), kind: "generated" },
    ...Object.entries(o.kit ?? {}).map(([path, text]): RnAppFile => ({ path: `src/kit/${path}`, text, kind: "kit" })),
  ];
  return { files, warnings: screens.warnings, theme, screens };
}

/** The packages an app on the kit needs, at the versions the kit is built and checked with (rn/package.json): what the
 *  export writes into apps/mobile/package.json. The test runner and the linter are the kit's own and left out. */
export function rnDependencies(): { dependencies: Record<string, string>; devDependencies: Record<string, string> } {
  const dev = rnPackage.devDependencies as Record<string, string>;
  const keep = ["@types/react", "eslint", "eslint-config-expo", "tailwindcss", "typescript"];
  return { dependencies: { ...(rnPackage.dependencies as Record<string, string>) }, devDependencies: Object.fromEntries(keep.filter((k) => dev[k]).map((k) => [k, dev[k]])) };
}

