/* Small pieces every target prints with. Words of a document or a contract reach code only through these: as an
 * escaped string (`str`), as JSON data (`jsonCode`), or as an identifier made of letters and digits
 * (lib/export/paths.ts). Never in a comment. */

import { str } from "../../parts/print";

export { str };

/** the first line of every file the export owns */
export const GENERATED = "// Generated by M3E Canvas. Do not edit: the next export rewrites this file (see AGENTS.md).";

/** a value as JSON a TypeScript or JavaScript file can hold, pretty-printed, with the line separators escaped */
export const jsonCode = (v: unknown, indent = 2) => (JSON.stringify(v, null, indent) ?? "null").replace(/[\u2028\u2029]/g, (c) => `\\u${c.charCodeAt(0).toString(16)}`);

/** a JSON file's text: two spaces, keys as given, a newline at the end */
export const jsonFile = (v: unknown) => `${JSON.stringify(v, null, 2)}\n`;

/** a key of an object literal: bare when it is a plain name, else an escaped string */
export const propKey = (k: string) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : str(k));

/** a value as code: an object literal with bare keys where they are names, spaced as code is written */
export function literal(v: unknown): string {
  if (Array.isArray(v)) return `[${v.map(literal).join(", ")}]`;
  if (v && typeof v === "object") {
    const entries = Object.entries(v as Record<string, unknown>).filter(([, x]) => x !== undefined);
    return entries.length ? `{ ${entries.map(([k, x]) => `${propKey(k)}: ${literal(x)}`).join(", ")} }` : "{}";
  }
  return str(v);
}

/** the keys of an object in order, as written into a package.json */
export const sortedObject = (o: Record<string, string>) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
