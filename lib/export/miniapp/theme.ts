import type { Doc } from "../../tokens";
import { rnThemeOf, type RnTheme } from "../rn/theme";

/* The theme an exported mini-program wears. It resolves exactly as the React Native app's does (lib/export/rn/theme.ts:
 * the document's colors in light and dark, its type ramp, corners, recipes, the style's own colors), and is written
 * twice: as the kit's `KitTheme` (numbers and recipes, and the colors for what is painted as a picture: icons), and as
 * a stylesheet of CSS variables every part's style reads (`var(--md-sys-color-primary)`), light on `.m3e-theme` and
 * dark on `.m3e-theme.m3e-dark`. The stylesheet has class selectors and custom properties only, so it is valid WXSS
 * (WeChat), TTSS (Douyin) and CSS (H5). */

export type MiniTheme = RnTheme;

export const miniThemeOf = (source: Pick<Doc, "theme" | "paletteKey" | "customPalette" | "styles">): MiniTheme => rnThemeOf(source);

const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

/** `#rrggbb[aa]` as "r, g, b", for the `-rgb` variable an opacity is laid over */
function rgb(hex: string): string | undefined {
  const m = /^#([0-9a-f]{3,8})$/i.exec(hex);
  if (!m) return undefined;
  let h = m[1];
  if (h.length <= 4) h = [...h].map((c) => c + c).join("");
  return `${parseInt(h.slice(0, 2), 16)}, ${parseInt(h.slice(2, 4), 16)}, ${parseInt(h.slice(4, 6), 16)}`;
}

/** a color as CSS: hex with an alpha as rgba (an old web view reads #rrggbbaa wrong) */
function cssColor(hex: string): string {
  const m = /^#([0-9a-f]{8})$/i.exec(hex);
  if (!m) return hex.toLowerCase();
  const a = Math.round((parseInt(m[1].slice(6, 8), 16) / 255) * 1000) / 1000;
  return `rgba(${rgb(hex)}, ${a})`;
}

/** the declarations of one mode: every role and its red, green and blue, and the style's own colors */
function declarations(mode: MiniTheme["light"]): string[] {
  const out: string[] = [];
  for (const [role, value] of Object.entries(mode.colors).sort(([a], [b]) => a.localeCompare(b))) {
    if (!/^[a-z][a-z0-9-]*$/.test(role) || !/^#[0-9a-f]{3,8}$/i.test(value)) continue;
    out.push(`  --md-sys-color-${role}: ${cssColor(value)};`, `  --md-sys-color-${role}-rgb: ${rgb(value)};`);
  }
  for (const [name, value] of Object.entries(mode.st).sort(([a], [b]) => a.localeCompare(b))) {
    if (!/^[a-zA-Z]+$/.test(name) || !/^#[0-9a-f]{3,8}$/i.test(value)) continue;
    out.push(`  --m3e-st-${kebab(name)}: ${cssColor(value)};`);
  }
  return out;
}

/** The theme as a stylesheet: light under `selector`, dark under it with `.m3e-dark`. */
export function themeCss(theme: MiniTheme, selector = ".m3e-theme"): string {
  if (!/^\.[a-z][a-z0-9-]*$/.test(selector)) throw new Error(`not a class selector: ${selector}`);
  return [
    `/* Generated by M3E Canvas from the design's theme (${theme.key}). Do not edit: change the design and export again. */`,
    "",
    `${selector} {`,
    ...declarations(theme.light),
    `  color-scheme: light;`,
    "}",
    "",
    `${selector}.m3e-dark {`,
    ...declarations(theme.dark),
    `  color-scheme: dark;`,
    "}",
    "",
  ].join("\n");
}
