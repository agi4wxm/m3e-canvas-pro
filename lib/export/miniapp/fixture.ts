  /* D5: layouts, ways of getting around, what floats */
  const layouts = withIds(next, layoutsDoc);
  const e = await printed("layouts", layouts.doc, layouts.widths);
  /* D3 */
  const f = await printed("inputs", withIds(next, inputsDoc).doc, {});
