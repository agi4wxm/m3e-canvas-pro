import { proofDoc } from "../../exportProject.fixture";
import { withIds, type Doc } from "../../tokens";
import { str } from "../../../parts/print";
import { kitsDoc, playDoc, splitsDoc } from "../rn/fixture";
import { callsModule, iconsModule, pageConfig, pageModule, printMiniApp, screensIndex, specModule, themeModule } from "./app";

/* Documents printed into the kit's own app (miniapp-kit/src/printed), so that what the printer writes is type-checked,
 * linted and built for WeChat, Douyin and H5 there, exactly as an exported mini-program would be: the export's proof
 * document (every kind of tap: variables, conditions, parts shown and hidden, a dialog, inputs, a dock, bars, a long
 * screen, the shop flow) under Material, and a screen of kits under iOS. They have no API: their calls are none. */

const HEAD = "// Generated by M3E Canvas. Do not edit: the next export rewrites this file (see AGENTS.md).";

const ROOT = (name: string) => `${HEAD}
import type { ReactNode } from "react";
import { RuntimeProvider, createRuntime } from "@m3e/app-runtime";
import { AppSpecProvider, ThemeProvider, registerIcons } from "../../kit";
import { icons } from "./icons";
import { SCREENS } from "./screens";
import { SPEC } from "./spec";
import { theme } from "./theme";
import "./theme.css";

registerIcons(icons);

/* a document with no API: every call answers 404 */
const runtime = createRuntime({ transport: { request: async () => ({ status: 404, headers: {}, body: undefined }) }, lang: "en", storageKey: ${str(`${name}:session`)} });

/** the printed document's providers: its runtime, its spec and its theme */
export function Root({ children }: { children?: ReactNode }) {
  return (
    <RuntimeProvider runtime={runtime}>
      <AppSpecProvider spec={SPEC} components={SCREENS}>
        <ThemeProvider theme={theme}>{children}</ThemeProvider>
      </AppSpecProvider>
    </RuntimeProvider>
  );
}
`;

/** a printed document's files, under miniapp-kit/src/printed/<name> */
async function printed(name: string, doc: Doc, widths: Record<string, number>): Promise<{ files: Record<string, string>; pages: string[] }> {
  const at = `miniapp-kit/src/printed/${name}`;
  const app = await printMiniApp(doc, widths, { kitImport: "../../../kit", callsImport: "../calls", scope: `m3e-printed-${name}`, pagePrefix: `printed/${name}/`, tabBar: false });
  const files: Record<string, string> = {
    [`${at}/theme.ts`]: themeModule(app.theme, "../../kit"),
    [`${at}/theme.css`]: app.css,
    [`${at}/icons.ts`]: iconsModule(app.icons, "../../kit"),
    [`${at}/calls.ts`]: callsModule(undefined, { apiImport: "", kitImport: "../../kit", runtimeFrom: "" }),
    [`${at}/spec.ts`]: specModule(doc, app.printed, undefined, { kitImport: "../../kit", callsFrom: "./calls" }),
    [`${at}/root.tsx`]: ROOT(name),
    ...Object.fromEntries(app.printed.screens.map((s) => [`${at}/screens/${s.component}.tsx`, s.source])),
    [`${at}/screens/index.ts`]: screensIndex(app.printed),
    [`${at}/warnings.json`]: `${JSON.stringify(app.printed.warnings, null, 1)}\n`,
  };
  for (const s of app.printed.screens) {
    files[`${at}/pages/${s.key}/index.tsx`] = pageModule(s.component, { rootFrom: "../../root", screenFrom: `../../screens/${s.component}` });
    files[`${at}/pages/${s.key}/index.config.ts`] = pageConfig(s);
  }
  return { files, pages: app.printed.screens.map((s) => s.path) };
}

/** every file of the test bed's printed documents, by its path from the repo's root */
export async function printedFixture(): Promise<Record<string, string>> {
  let n = 0;
  const next = () => `id${++n}`;
  const proof = withIds(next, proofDoc);
  const kits = withIds(next, kitsDoc);
  const splits = withIds(next, splitsDoc);
  const a = await printed("proof", proof.doc, proof.widths);
  const b = await printed("kits", kits.doc, kits.widths);
  const c = await printed("splits", splits.doc, splits.widths);
  /* D4: the game parts, actions and menus */
  const play = withIds(next, playDoc);
  const d = await printed("play", play.doc, play.widths);
  return {
    ...a.files,
    ...b.files,
    ...c.files,
    ...d.files,
    "miniapp-kit/src/printed/pages.ts": `${HEAD}\n\n/** the pages of the printed documents, for the app's config */\nexport const PRINTED_PAGES: string[] = ${JSON.stringify([...a.pages, ...b.pages, ...c.pages, ...d.pages], null, 2)};\n`,
  };
}
