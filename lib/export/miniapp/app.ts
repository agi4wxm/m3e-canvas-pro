/** the screens by their key */
export function screensIndex(printed: MiniScreens): string {
  return [
    HEAD,
    'import type { ComponentType } from "react";',
    "",
    ...printed.screens.map((s) => `import { ${s.component} } from ${str(`./${s.component}`)};`),
    "",
    "/** every screen, by the key a tap goes to it by */",
    `export const SCREENS: Record<string, ComponentType> = { ${printed.screens.map((s) => `${s.key}: ${s.component}`).join(", ")} };`,
    "",
  ].join("\n");
}

/* ---------- the contract's calls ---------- */

const record = (v: unknown): Record<string, unknown> => (v && typeof v === "object" && !Array.isArray(v) ? (v as Record<string, unknown>) : {});

/** an operation's parameters by where they go, from its OpenAPI path item (the path's own and the operation's, a
 *  `$ref` to the reusable ones followed) */
function paramPlaces(openapi: Record<string, unknown>, op: ApiOperation): { query: string[]; header: string[] } {
  const item = record(record(openapi.paths)[op.path]);
  const method = record(item[op.method.toLowerCase()]);
  const shared = record(record(openapi.components).parameters);
  const resolve = (p: unknown) => {
    const ref = record(p).$ref;
    return typeof ref === "string" && ref.startsWith("#/components/parameters/") ? record(shared[ref.slice("#/components/parameters/".length)]) : record(p);
  };
  const all = [...(Array.isArray(item.parameters) ? item.parameters : []), ...(Array.isArray(method.parameters) ? method.parameters : [])].map(resolve);
  const names = (where: string) => [...new Set(all.filter((p) => p.in === where && typeof p.name === "string").map((p) => p.name as string))];
  return { query: names("query"), header: names("header") };
}

/** whether an operation takes a body the typed client does not type (multipart, a file) */
function untypedBody(openapi: Record<string, unknown>, op: ApiOperation): boolean {
  if (op.body) return false;
  const method = record(record(record(openapi.paths)[op.path])[op.method.toLowerCase()]);
  return Object.keys(record(method.requestBody)).length > 0;
}

/** The calls a screen makes, one per operation of the contract: the arguments by name put where the operation takes
 *  them (its path, its query, its headers, the rest as fields of its JSON body), sent with the typed client. */
export function callsModule(api: ApiModel | undefined, o: { apiImport: string; kitImport: string; runtimeFrom: string }): string {
  const ops = api?.operations ?? [];
  const lines = ops.map((op) => {
    const places = api ? paramPlaces(api.openapi, op) : { query: [], header: [] };
    const known = [...op.params, ...places.query, ...places.header];
    const parts: string[] = [];
    if (op.params.length) parts.push(`params: { ${op.params.map((p) => `${str(p)}: seg(a[${str(p)}])`).join(", ")} }`);
    if (op.query) parts.push(`query: pick(a, ${expr(places.query)})`);
    if (op.body) parts.push(`body: (b ?? omit(a, ${expr(known)})) as In<${str(op.name)}>["body"]`);
    const init = places.header.length ? `{ ...i, headers: headers(a, ${expr(places.header)}) }` : "i";
    if (untypedBody(api!.openapi, op)) {
      /* the path's words as strings, each parameter's value between them */
      const path = op.path
        .split(/(\{[^{}/]+\})/)
        .filter(Boolean)
        .map((part) => (/^\{[^{}/]+\}$/.test(part) ? `encodeURIComponent(String(seg(a[${str(part.slice(1, -1))}])))` : str(part)))
        .join(" + ");
      return `  ${str(op.operationId)}: (a, b, i) => api.request({ operationId: ${str(op.operationId)}, method: ${str(op.method)}, path: ${path || '""'}, ${op.query ? `query: pick(a, ${expr(places.query)}), ` : ""}body: b ?? omit(a, ${expr(known)}), ...${init} }),`;
    }
    const input = parts.length ? `{ ${parts.join(", ")} }` : op.query ? "{}" : undefined;
    return `  ${str(op.operationId)}: (${parts.length || op.query ? "a" : "_a"}, ${op.body ? "b" : "_b"}, i) => ${clientCallCode("api", op, input, init)},`;
  });
  const usesSeg = lines.some((l) => l.includes("seg("));
  const usesPick = lines.some((l) => l.includes("pick("));
  const usesOmit = lines.some((l) => l.includes("omit("));
  const usesHeaders = lines.some((l) => l.includes("headers("));
  return [
    HEAD,
    api && ops.length ? `import { createApi${ops.some((op) => op.body) ? ", type Api" : ""} } from ${str(o.apiImport)};` : "",
    `import type { CallFn } from ${str(o.kitImport)};`,
    api && ops.length ? `import { runtime } from ${str(o.runtimeFrom)};` : "",
    "",
    ...(api && ops.length
      ? [
          "/** the API as the screens call it: the typed client over the runtime's transport (the session's tokens on it) */",
          "export const api = createApi(runtime.transport);",
          "",
          ...(ops.some((op) => op.body) ? ["type In<K extends keyof Api> = Exclude<Parameters<Api[K]>[0], undefined>;", ""] : []),
          ...(usesSeg ? ["/** a path parameter: words or a number */", "const seg = (v: unknown): string | number => (typeof v === \"number\" ? v : v === undefined || v === null ? \"\" : String(v));", ""] : []),
          ...(usesPick ? ["/** the arguments that are query parameters, as the query takes them */", "const pick = (a: Record<string, unknown>, names: string[]) => Object.fromEntries(names.filter((n) => a[n] !== undefined && a[n] !== null && a[n] !== \"\").map((n) => [n, typeof a[n] === \"number\" || typeof a[n] === \"boolean\" ? a[n] : String(a[n])])) as Record<string, string | number | boolean>;", ""] : []),
          ...(usesOmit ? ["/** the arguments that are no parameter: the fields of the body */", "const omit = (a: Record<string, unknown>, names: string[]) => Object.fromEntries(Object.entries(a).filter(([k]) => !names.includes(k)));", ""] : []),
          ...(usesHeaders ? ["/** the arguments that are header parameters */", "const headers = (a: Record<string, unknown>, names: string[]) => Object.fromEntries(names.filter((n) => a[n] !== undefined && a[n] !== null).map((n) => [n, String(a[n])]));", ""] : []),
        ]
      : []),
    "/** each operation of the contract, by its id, as a tap or a screen's data calls it */",
    `export const CALLS: Record<string, CallFn> = {`,
    ...lines,
    "};",
    "",
  ]
    .filter((l, i, all) => !(l === "" && all[i - 1] === ""))
    .join("\n");
}

/** The app's own: its screens and their pages, where it starts, the variables, the calls and the sign-in. */
export function specModule(doc: Doc, printed: MiniScreens, api: ApiModel | undefined, o: { kitImport: string; callsFrom: string }): string {
  const screens = Object.fromEntries(
    printed.screens.map((s) => [s.key, { path: s.path, ...(s.params ? { params: s.params.map((p) => ({ name: p.name, ...(p.type ? { type: p.type } : {}), ...(p.example !== undefined ? { example: p.example } : {}) })) } : {}), ...(s.auth ? { auth: s.auth } : {}), ...(s.tab !== undefined ? { tab: s.tab } : {}) }]),
  );
  const vars = (doc.vars ?? []).map((v) => ({ id: v.id, name: v.name, type: v.type, value: v.value }));
  const status = Object.fromEntries((api?.operations ?? []).map((op) => [op.operationId, op.status]));
  const login = doc.api?.auth?.login;
  return [
    HEAD,
    `import type { AppSpec } from ${str(o.kitImport)};`,
    `import { CALLS } from ${str(o.callsFrom)};`,
    "",
    "export const SPEC: AppSpec = {",
    `  screens: ${expr(screens)},`,
    `  start: ${str(printed.initial)},`,
    `  vars: ${expr(vars)},`,
    "  calls: CALLS,",
    `  status: ${expr(status)},`,
    ...(login ? [`  login: ${str(login)},`] : []),
    "};",
    "",
  ].join("\n");
}

/** a page: the screen inside the app's providers, and its page's config (its title, a custom navigation bar, a pull) */
export const pageModule = (component: string, o: { rootFrom: string; screenFrom: string }) =>
  `${HEAD}\nimport { Root } from ${str(o.rootFrom)};\nimport { ${component} } from ${str(o.screenFrom)};\n\nexport default function Page() {\n  return (\n    <Root>\n      <${component} />\n    </Root>\n  );\n}\n`;

export const pageConfig = (s: { title: string; pull: boolean }, dark = false) =>
  `${HEAD}\nexport default definePageConfig(${JSON.stringify({ navigationBarTitleText: s.title.slice(0, 60), navigationStyle: "custom", ...(s.pull ? { enablePullDownRefresh: true, backgroundTextStyle: dark ? "light" : "dark" } : {}) })});\n`;

/** the tab bar's component: the design's navigation bar, its chosen item the screen on show, a tap switching tabs */
export function tabBarModule(tab: NonNullable<MiniScreens["tabBar"]>, o: { kitImport: string; specFrom: string }): string {
  const items = tab.items.map((x) => x.screen ?? null);
  return [
    HEAD,
    "import Taro from \"@tarojs/taro\";",
    `import { NavigationBar, ThemeRoot, currentPlace, openPlace, useAppSpec } from ${str(o.kitImport)};`,
    "",
    "/** the screen each item of the bar switches to (none where the design's item goes nowhere) */",
    `const TABS: (string | null)[] = ${expr(items)};`,
    "",
    "/** The app's tab bar: the design's navigation bar, at the foot of every tab's page (the mini-program's custom tab",
    " *  bar), its chosen item the screen on show. */",
    "export function TabBar() {",
    "  const { spec } = useAppSpec();",
    "  const here = currentPlace(spec)?.screen;",
    "  const selected = Math.max(0, TABS.indexOf(here ?? null));",
    "  return (",
    "    <ThemeRoot>",
    "      <NavigationBar",
    `        ${tab.props}`,
    "        selected={selected}",
    "        onChange={(i) => {",
    "          const to = TABS[i];",
    "          if (to && to !== here) void openPlace(spec, { screen: to });",
    "          else if (!to) void Taro.showToast({ title: \"…\", icon: \"none\" });",
    "        }}",
    "      />",
    "    </ThemeRoot>",
    "  );",
    "}",
    "",
  ].join("\n");
}

/** the icons the screens, the kit and the tab bar draw, in the theme's family, with the document's own drawings */
export async function iconData(doc: Doc, theme: MiniTheme, printed: MiniScreens) {
  const icons = await rnIconData([theme.icons], [...printed.icons, ...KIT_ICONS]);
  for (const [id, markup] of Object.entries(doc.icons ?? {})) {
    const box = /viewBox="([\d.\s-]+)"/.exec(markup)?.[1]?.trim().split(/\s+/).map(Number);
    const body = markup.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
    icons.glyphs[`m3e-doc:${id}`] = [body, box?.[2] ?? 24, box?.[3] ?? 24];
  }
  return icons;
}

export type PrintedMiniApp = { printed: MiniScreens; theme: MiniTheme; css: string; icons: Awaited<ReturnType<typeof iconData>> };

/** the screens, the theme and its stylesheet, and the icons of a document */
export async function printMiniApp(doc: Doc, widths: Record<string, number>, o: MiniPrintOptions & { scope?: string; pagePrefix?: string } = {}): Promise<PrintedMiniApp> {
  const printed = printMiniScreens(doc, widths, o);
  if (o.pagePrefix) for (const s of printed.screens) s.path = `${o.pagePrefix}${s.path}`;
  const theme = { ...miniThemeOf(doc), ...(o.scope ? { scope: o.scope } : {}) };
  const css = themeCss(theme, `.${o.scope ?? "m3e-theme"}`);
  return { printed, theme, css, icons: await iconData(doc, theme, printed) };
}
