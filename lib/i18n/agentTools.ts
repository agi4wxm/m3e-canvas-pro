const AT: Record<Lang, number> = { en: 0, zh: 1, ja: 2, ko: 3 };

/** a tool's name for the step list; one this table does not know reads as its words */
export function toolLabel(name: string, lang: Lang): string {
  const four = L[name];
  if (four) return four[AT[lang]];
  const words = name.replace(/_/g, " ");
  return words.charAt(0).toUpperCase() + words.slice(1);
}

