// bun run gen:rn        (bun run check:rn to only check)
//
// Writes the data the React Native kit (rn/) takes from the editor: every part's props and their defaults, the vector
// shapes, Material's theme as the kit's default, and for the kit's gallery the themes of the styles it is checked under,
// the glyphs it draws and the trees of atoms the composites without a component of the kit's own split into. The kit is
// its own package and never imports the editor; what it needs is written here, and `check:rn` fails when it is behind.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { setGlobalLang, type Lang } from "../lib/i18n";
import { CATEGORIES, PARTS, reader, tierOf } from "../parts/registry";
import { KITS, pickVariant } from "../parts/kits";
import { SVG_PRESETS } from "../parts/svg";
import { SHAPE_NAMES, shapeClipPath } from "../lib/m3e/shape-library";
import { kitLookOf } from "../lib/kits";
import { normalizeTheme } from "../lib/tokens";
import { rnThemeOf } from "../lib/export/rn/theme";
import { rnIconData } from "../lib/export/rn/icons";
import { SET_ONLY, plainTree, propValues, type PlainNode } from "../lib/export/rn/data";
import { iconNamesOf } from "../lib/export/rn/print";
import { printedFixture } from "../lib/export/rn/fixture";
import { NATIVE, kitPropName } from "../rn/src/kit/coverage";
import { KIT_ICONS } from "../rn/src/kit/icons/names";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const LANG: Lang = "en";
setGlobalLang(LANG);

/** the styles the kit's gallery draws every part under: Material, iOS, WeChat and a dark one */
export const GALLERY_STYLES = ["material", "ios", "wechat", "spotify"] as const;

const HEAD = "// Generated by scripts/gen-rn.ts (bun run gen:rn). Do not edit.\n";
const json = (v: unknown) => JSON.stringify(v, null, 1);

function themeOf(key: string) {
  return rnThemeOf({ theme: normalizeTheme(key === "material" ? undefined : { style: key }), paletteKey: "purple" });
}

/** every part's props as the canvas reads them with nothing set, by part */
function partsModule(): string {
  /* under the names the kit takes them by (`style` is React Native's) */
  const renamed = (slug: string, v: Record<string, unknown>) => Object.fromEntries(Object.entries(v).filter(([k]) => !SET_ONLY.has(k)).map(([k, x]) => [kitPropName(slug, k), x]));
  const parts = Object.fromEntries(PARTS.map((d) => [d.slug, { name: d.name, tier: tierOf(d), category: d.category, defaults: renamed(d.slug, propValues(d, {})) }]));
  return `${HEAD}
/** every part of the editor: its name, tier, section and the value of each prop when nothing is set (in English) */
export type PartInfo = { name: string; tier: "atom" | "composite"; category: string; defaults: Record<string, unknown> };

export const PARTS: Record<string, PartInfo> = ${json(parts)};

/** the palette's sections, in its order: the atoms first */
export const CATEGORIES: string[] = ${json([...CATEGORIES])};
`;
}

/** a shape's clip-path polygon (in percent) as a path in a 100 × 100 box */
function shapePaths(): Record<string, string> {
  return Object.fromEntries(
    SHAPE_NAMES.map((name) => {
      const points = [...shapeClipPath(name).matchAll(/([\d.]+)% ([\d.]+)%/g)].map((m) => `${m[1]} ${m[2]}`);
      return [name, `M${points.join("L")}Z`];
    }),
  );
}

function shapesModule(): string {
  const presets = Object.fromEntries(Object.entries(SVG_PRESETS).map(([k, v]) => [k, { viewBox: v.viewBox, d: v.d, ...(v.stroke !== undefined ? { stroke: v.stroke } : {}) }]));
  return `${HEAD}
/** the vector part's library of shapes (parts/svg.ts) */
export const SVG_PRESETS: Record<string, { viewBox: string; d: string[]; stroke?: number }> = ${json(presets)};

/** M3 Expressive's shapes as the canvas clips them (lib/m3e/shape-library.ts \`shapeClipPath\`), each a path in a 100 × 100 box */
export const SHAPE_PATHS: Record<string, string> = ${json(shapePaths())};
`;
}

const defaultThemeModule = () => `${HEAD}
import type { KitTheme } from "./types";

/** Material 3 with M3's baseline colors: what the kit wears with no theme of its own */
export const MATERIAL: KitTheme = ${json(themeOf("material"))};
`;

/** the trees of atoms each composite the kit draws no component for splits into, and each kit in the variant a style
 *  picks, under every style of the gallery */
function treesOf() {
  const out: Record<string, { splits: Record<string, PlainNode>; kits: Record<string, { variant: string; category: string; tree: PlainNode }> }> = {};
  for (const key of GALLERY_STYLES) {
    const look = kitLookOf(normalizeTheme(key === "material" ? undefined : { style: key }));
    const splits: Record<string, PlainNode> = {};
    for (const d of PARTS) {
      if (Object.prototype.hasOwnProperty.call(NATIVE, d.slug) || !d.atoms) continue;
      splits[d.slug] = plainTree(d.atoms(reader(d, {}), look) as Parameters<typeof plainTree>[0], LANG);
    }
    const kits: Record<string, { variant: string; category: string; tree: PlainNode }> = {};
    for (const k of KITS) {
      const v = pickVariant(k, look);
      kits[k.slug] = { variant: v.key, category: k.category, tree: plainTree(v.build(look), LANG) };
    }
    out[key] = { splits, kits };
  }
  return out;
}

/** every icon name a tree or a value names */
function namesIn(v: unknown, into: Set<string>) {
  if (Array.isArray(v)) v.forEach((x) => namesIn(x, into));
  else if (v && typeof v === "object") {
    const n = v as PlainNode;
    if (typeof n.slug === "string" && n.props) for (const name of iconNamesOf(n.slug, n.props)) into.add(name);
    for (const x of Object.values(v)) namesIn(x, into);
  }
}

async function galleryModules(): Promise<Record<string, string>> {
  const themes = Object.fromEntries(GALLERY_STYLES.map((k) => [k, themeOf(k)]));
  const trees = treesOf();
  const names = new Set<string>(KIT_ICONS);
  for (const d of PARTS) for (const n of iconNamesOf(d.slug, propValues(d, {}))) names.add(n);
  namesIn(trees, names);
  const icons = await rnIconData(Object.values(themes).map((t) => t.icons), names);
  return {
    "rn/src/gallery/themes.generated.ts": `${HEAD}
import type { KitTheme } from "../kit";

export type GalleryStyle = ${GALLERY_STYLES.map((k) => JSON.stringify(k)).join(" | ")};

/** the styles the gallery draws every part under */
export const THEMES: Record<GalleryStyle, KitTheme> = ${json(themes)};
`,
    "rn/src/gallery/icons.generated.ts": `${HEAD}
import type { IconData } from "../kit";

/** the glyphs of every name the gallery draws, in the families of its styles */
export const ICONS: IconData = ${JSON.stringify(icons)};
`,
    "rn/src/gallery/trees.generated.ts": `${HEAD}
import type { TreeNode } from "../kit";

/** under each style: the trees of atoms the composites without a component split into, and each kit as the style composes it */
export const TREES: Record<string, { splits: Record<string, TreeNode>; kits: Record<string, { variant: string; category: string; tree: TreeNode }> }> = ${JSON.stringify(trees)};
`,
  };
}

async function main() {
  const check = process.argv.includes("--check");
  const files: Record<string, string> = {
    "rn/src/kit/parts.generated.ts": partsModule(),
    "rn/src/kit/shapes.generated.ts": shapesModule(),
    "rn/src/kit/theme/default.generated.ts": defaultThemeModule(),
    ...(await galleryModules()),
    ...(await printedFixture()),
  };
  const stale: string[] = [];
  for (const [path, text] of Object.entries(files)) {
    const at = join(root, path);
    const now = existsSync(at) ? readFileSync(at, "utf8") : "";
    if (now === text) continue;
    if (check) stale.push(path);
    else {
      mkdirSync(dirname(at), { recursive: true });
      writeFileSync(at, text);
      console.log(`wrote ${path}`);
    }
  }
  if (stale.length) {
    console.error(`out of date (run bun run gen:rn):\n  ${stale.join("\n  ")}`);
    process.exit(1);
  }
}

await main();
