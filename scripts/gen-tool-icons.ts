/* Writes lib/tools/icons.generated.ts: the Material names every icon family draws offline, and for each product family
 * the names it has no drawing of its own for (those are drawn from Rounded). Read from the bundled icon sets, so it
 * follows `bun run gen:icon-sets`; lib/tools/tools.test.ts checks it is up to date. Run with bun. */

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const DATA = fileURLToPath(new URL("../components/m3e/icon-sets/data/", import.meta.url));
const OUT = fileURLToPath(new URL("../lib/tools/icons.generated.ts", import.meta.url));

type Shard = { map?: Record<string, unknown>; sets?: { icons: Record<string, unknown>; aliases?: Record<string, unknown> }[] };

const snake = (n: string) => n.replaceAll("-", "_");

export function iconTables(): { names: string[]; lacks: Record<string, string[]> } {
  const files = readdirSync(DATA).filter((f) => /^[a-z]+-\d+\.json$/.test(f));
  const read = (f: string) => JSON.parse(readFileSync(DATA + f, "utf8")) as Shard;
  const names = new Set<string>();
  for (const f of files.filter((x) => x.startsWith("rounded-")))
    for (const set of read(f).sets ?? []) for (const id of [...Object.keys(set.icons), ...Object.keys(set.aliases ?? {})]) names.add(snake(id.replace(/(-outline)?-rounded$/, "")));
  const all = [...names].sort();
  const has = new Map<string, Set<string>>();
  for (const f of files) {
    const map = read(f).map;
    if (!map) continue;
    const family = f.replace(/-\d+\.json$/, "");
    const own = has.get(family) ?? new Set<string>();
    for (const k of Object.keys(map)) own.add(snake(k));
    has.set(family, own);
  }
  const lacks = Object.fromEntries([...has].sort(([a], [b]) => (a < b ? -1 : 1)).map(([family, own]) => [family, all.filter((n) => !own.has(n))]));
  return { names: all, lacks };
}

export function iconSource(): string {
  const { names, lacks } = iconTables();
  return `// Generated by scripts/gen-tool-icons.ts (bun scripts/gen-tool-icons.ts). Do not edit.
/** the Material Symbols names every icon family draws offline, snake_case */
export const ICON_NAMES = ${JSON.stringify(names.join(" "))};

/** for each product family, the names it has no drawing of its own for: those are drawn from Rounded */
export const FAMILY_LACKS: Record<string, string> = ${JSON.stringify(Object.fromEntries(Object.entries(lacks).map(([k, v]) => [k, v.join(" ")])), null, 2)};
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUT, iconSource());
  console.log(`wrote ${OUT}`);
}
