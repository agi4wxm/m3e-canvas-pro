// bun run gen:versions        (bun run check:versions to only check)
//
// Writes lib/versions.generated.ts: the exact version of each package an exported project may name, read off
// package.json and bun.lock. The export pins these (lib/exportProject.ts), so the editor carries a table of a few
// dozen versions instead of the whole lockfile. A range in package.json is only what this repo accepts; the lockfile
// says what it runs. lib/versions.test.ts fails when the table is behind either file.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { EXPORT_ALWAYS, EXPORT_DEV } from "../lib/exportPackages";

type Manifest = { dependencies?: Record<string, string>; devDependencies?: Record<string, string> };

/** the version the lockfile resolved `name` to; an alias in package.json (`npm:…`) says exactly what it is */
export function lockedVersion(pkg: Manifest, lock: string, name: string): string {
  const range = { ...pkg.dependencies, ...pkg.devDependencies }[name];
  if (range?.startsWith("npm:")) return range;
  const escaped = name.replace(/[.*+?^${}()|[\]\\/]/g, "\\$&");
  const at = new RegExp(`"${escaped}": \\["${escaped}@([^"]+)"`).exec(lock);
  if (at) return at[1];
  throw new Error(`no version of ${name} in bun.lock`);
}

/** Every package an exported project may name: what the copied files can import (this repo's dependencies), what it
 *  always needs, and what it builds with. Each at the version this repo runs, sorted by name. */
export function versionTable(pkg: Manifest, lock: string): Record<string, string> {
  const names = new Set([...Object.keys(pkg.dependencies ?? {}), ...EXPORT_ALWAYS, ...EXPORT_DEV]);
  return Object.fromEntries([...names].sort().map((name) => [name, lockedVersion(pkg, lock, name)]));
}

/** the module, as written */
export function versionModule(table: Record<string, string>): string {
  return [
    "// Generated by scripts/gen-versions.ts (bun run gen:versions) from package.json and bun.lock. Do not edit.",
    "",
    "/** the exact version of each package an exported project may name: what this repo runs, out of its lockfile (an alias as",
    " *  package.json gives it) */",
    "export const VERSIONS: Record<string, string> = {",
    ...Object.entries(table).map(([name, version]) => `  ${JSON.stringify(name)}: ${JSON.stringify(version)},`),
    "};",
    "",
  ].join("\n");
}

if (import.meta.main) {
  const root = join(dirname(fileURLToPath(import.meta.url)), "..");
  const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8")) as Manifest;
  const text = versionModule(versionTable(pkg, readFileSync(join(root, "bun.lock"), "utf8")));
  const out = join(root, "lib", "versions.generated.ts");
  if (process.argv.includes("--check")) {
    if (readFileSync(out, "utf8") !== text) {
      console.error("lib/versions.generated.ts is behind package.json or bun.lock: run bun run gen:versions");
      process.exit(1);
    }
    console.log("lib/versions.generated.ts is up to date");
  } else {
    writeFileSync(out, text);
    console.log(`wrote lib/versions.generated.ts (${text.split("\n").filter((l) => l.startsWith("  ")).length} packages)`);
  }
}
