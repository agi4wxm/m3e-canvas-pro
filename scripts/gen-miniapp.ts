// bun run gen:miniapp        (bun run check:miniapp to only check)
//
// Writes the data the mini-program kit (miniapp-kit/) takes from the editor: the props and defaults of every part it
// draws, the vector shapes, Material's theme as the kit's default, and for its gallery the themes of the styles it is
// checked under (as the kit reads them and as their stylesheets), the glyphs it draws, and the documents printed by
// lib/export/miniapp into its own app (miniapp-kit/src/printed) so the printer's output is type-checked, linted and
// built for WeChat, Douyin and H5 there. The kit is its own package and never imports the editor; `check:miniapp` fails
// when what is written here is behind.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { setGlobalLang, type Lang } from "../lib/i18n";
import { PARTS, tierOf } from "../parts/registry";
import { SVG_PRESETS } from "../parts/svg";
import { SHAPE_NAMES, shapeClipPath } from "../lib/m3e/shape-library";
import { normalizeTheme } from "../lib/tokens";
import { rnIconData } from "../lib/export/rn/icons";
import { SET_ONLY, propValues } from "../lib/export/rn/data";
import { iconNamesOf } from "../lib/export/rn/print";
import { miniThemeOf, themeCss } from "../lib/export/miniapp/theme";
import { printedFixture } from "../lib/export/miniapp/fixture";
import { KIT_ICONS } from "../miniapp-kit/src/kit/iconNames";
import { NATIVE, kitPropName } from "../miniapp-kit/src/kit/coverage";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const LANG: Lang = "en";
setGlobalLang(LANG);

/** the styles the kit's gallery draws every part under: Material, iOS, WeChat and a dark one */
export const GALLERY_STYLES = ["material", "ios", "wechat", "spotify"] as const;

const HEAD = "// Generated by scripts/gen-miniapp.ts (bun run gen:miniapp). Do not edit.\n";
const json = (v: unknown) => JSON.stringify(v, null, 1);

const themeOf = (key: string) => miniThemeOf({ theme: normalizeTheme(key === "material" ? undefined : { style: key }), paletteKey: "purple" });

/** the props of every part the kit draws, as the canvas reads them with nothing set */
function partsModule(): string {
  const renamed = (slug: string, v: Record<string, unknown>) => Object.fromEntries(Object.entries(v).filter(([k]) => !SET_ONLY.has(k)).map(([k, x]) => [kitPropName(slug, k), x]));
  const parts = Object.fromEntries(PARTS.filter((d) => Object.prototype.hasOwnProperty.call(NATIVE, d.slug)).map((d) => [d.slug, { name: d.name, tier: tierOf(d), defaults: renamed(d.slug, propValues(d, {})) }]));
  return `${HEAD}
/** every part the kit draws: its name, tier and the value of each prop when nothing is set (in English) */
export type PartInfo = { name: string; tier: "atom" | "composite"; defaults: Record<string, unknown> };

export const PARTS: Record<string, PartInfo> = ${json(parts)};
`;
}

function shapesModule(): string {
  const presets = Object.fromEntries(Object.entries(SVG_PRESETS).map(([k, v]) => [k, { viewBox: v.viewBox, d: v.d, ...(v.stroke !== undefined ? { stroke: v.stroke } : {}) }]));
  const paths = Object.fromEntries(
    SHAPE_NAMES.map((name) => {
      const points = [...shapeClipPath(name).matchAll(/([\d.]+)% ([\d.]+)%/g)].map((m) => `${m[1]} ${m[2]}`);
      return [name, `M${points.join("L")}Z`];
    }),
  );
  return `${HEAD}
/** the vector part's library of shapes (parts/svg.ts) */
export const SVG_PRESETS: Record<string, { viewBox: string; d: string[]; stroke?: number }> = ${json(presets)};

/** M3 Expressive's shapes as the canvas clips them (lib/m3e/shape-library.ts \`shapeClipPath\`), each a path in a 100 × 100 box */
export const SHAPE_PATHS: Record<string, string> = ${json(paths)};
`;
}

const defaultThemeModule = () => `${HEAD}
import type { KitTheme } from "./theme";

/** Material 3 with M3's baseline colors: what the kit wears with no theme of its own */
export const MATERIAL: KitTheme = ${json(themeOf("material"))};
`;

async function galleryModules(): Promise<Record<string, string>> {
  const themes = Object.fromEntries(GALLERY_STYLES.map((k) => [k, themeOf(k)]));
  const names = new Set<string>(KIT_ICONS);
  for (const d of PARTS) if (Object.prototype.hasOwnProperty.call(NATIVE, d.slug)) for (const n of iconNamesOf(d.slug, propValues(d, {}))) names.add(n);
  const icons = await rnIconData(Object.values(themes).map((t) => t.icons), names);
  return {
    "miniapp-kit/src/gallery/themes.generated.ts": `${HEAD}
import type { KitTheme } from "../kit";

export type GalleryStyle = ${GALLERY_STYLES.map((k) => JSON.stringify(k)).join(" | ")};

/** the styles the gallery draws every part under */
export const THEMES: Record<GalleryStyle, KitTheme> = ${json(themes)};
`,
    "miniapp-kit/src/gallery/themes.generated.css": GALLERY_STYLES.map((k) => themeCss(themes[k], `.m3e-gallery-${k}`)).join("\n"),
    "miniapp-kit/src/gallery/icons.generated.ts": `${HEAD}
import type { IconData } from "../kit";

/** the glyphs of every name the gallery draws, in the families of its styles */
export const ICONS: IconData = ${JSON.stringify(icons)};
`,
  };
}

async function main() {
  const check = process.argv.includes("--check");
  const files: Record<string, string> = {
    "miniapp-kit/src/kit/parts.generated.ts": partsModule(),
    "miniapp-kit/src/kit/shapes.generated.ts": shapesModule(),
    "miniapp-kit/src/kit/theme.generated.ts": defaultThemeModule(),
    ...(await galleryModules()),
    ...(await printedFixture()),
  };
  const stale: string[] = [];
  for (const [path, text] of Object.entries(files)) {
    const at = join(root, path);
    const now = existsSync(at) ? readFileSync(at, "utf8") : "";
    if (now === text) continue;
    if (check) stale.push(path);
    else {
      mkdirSync(dirname(at), { recursive: true });
      writeFileSync(at, text);
      console.log(`wrote ${path}`);
    }
  }
  if (stale.length) {
    console.error(`out of date (run bun run gen:miniapp):\n  ${stale.join("\n  ")}`);
    process.exit(1);
  }
}

await main();
