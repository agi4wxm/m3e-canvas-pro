type Seed = Labels["zh"];
const say = (label: string) => (WORDS[label] ? { labels: WORDS[label] } : {});
const text = (key: string, label: string, value: string, zh?: Seed, multiline?: boolean): PropDef => ({ key, label, ...say(label), kind: "text", default: value, ...(zh ? { defaults: { zh } } : {}), ...(multiline ? { multiline } : {}) });
const num = (key: string, label: string, value: number, min: number, max: number, step = 1): PropDef => ({ key, label, ...say(label), kind: "number", default: value, min, max, step });
const flag = (key: string, label: string, value: boolean): PropDef => ({ key, label, ...say(label), kind: "bool", default: value });
const pick = (key: string, label: string, value: string, options: string[]): PropDef => ({ key, label, ...say(label), kind: "enum", default: value, options });
const icon = (key: string, label: string, value: string): PropDef => ({ key, label, ...say(label), kind: "icon", default: value });
const image = (key: string, label: string): PropDef => ({ key, label, ...say(label), kind: "image" });
const list = (key: string, label: string, value: ListItem[], max: number, icons = false): PropDef => ({ key, label, ...say(label), kind: "list", default: value, max, icons });
const table = (key: string, label: string, value: TableData): PropDef => ({ key, label, ...say(label), kind: "table", default: value });
const WIDTH = (value: number, min = 200, max = 960): PropDef => ({ key: "width", label: "Width", kind: "number", default: value, min, max, step: 4, unit: "px" });
const HEIGHT = (value: number, min = 80, max = 960): PropDef => ({ key: "height", label: "Height", kind: "number", default: value, min, max, step: 4, unit: "px" });
const SELECTED = num("selected", "Open row (-1: none)", -1, -1, 99);

const px = (p: P, key = "width") => Math.round(p.n(key));
const rowsOf = (p: P, key = "data") => p.table(key).rows;
const words = (items: ListItem[]) => items.map((x) => x.label);
const withIcons = (items: ListItem[]) => items.map((x) => ({ label: x.label, ...(x.icon ? { icon: x.icon } : {}) }));
const rowSlots = (rows: string[][], column = 0): PartSlot[] => rows.map((r, i) => ({ key: `tab:${i}`, label: r[column] || `${i + 1}` }));
const slot = (key: string, label: string, ...on: boolean[]): PartSlot[] => (on.every(Boolean) ? [{ key, label }] : []);

